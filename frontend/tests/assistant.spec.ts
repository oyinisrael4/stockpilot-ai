import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'

test('assistant reads database figures and posts only the explicitly confirmed preview', async ({ page }, info) => {
  test.setTimeout(70_000)
  await page.setViewportSize({ width: 1440, height: 950 })
  const username = 'assistant-' + randomUUID().slice(0, 8)
  await page.goto('/register')
  await page.getByLabel('Business name').fill('Harbor Water Supply · Assistant Test')
  await page.getByLabel('Username').fill(username)
  await page.getByLabel('Email').fill(username + '@example.invalid')
  await page.getByLabel('Password', { exact: true }).fill('Fixture!Wavelength459')
  if (await page.getByLabel('Confirm Password', { exact: true }).count()) await page.getByLabel('Confirm Password', { exact: true }).fill('Fixture!Wavelength459')
await page.getByRole('button', { name: 'Create workspace' }).click()
  await expect(page.getByRole('heading', { name: 'Overview' })).toBeVisible()

  const [business] = await (await page.request.get('/api/v1/businesses/')).json()
  const token = (await page.context().cookies()).find(cookie => cookie.name === 'csrftoken')!
  const endpoint = '/api/v1/businesses/' + business.id + '/'
  async function fixture(resource: string, data: object) {
    const response = await page.request.post(endpoint + resource, { data, headers: { 'X-CSRFToken': token.value } })
    expect(response.ok(), 'Fixture ' + resource).toBe(true)
    return response.json()
  }
  const product = await fixture('products/', { name: 'Bottled Water (75cl)', sku: 'WATER-75', price: '250', reorder_level: '10' })
  await fixture('movements/', { product: product.id, quantity: '100', unit_cost: '150' })
  const low = await fixture('products/', { name: 'Water Case (12 pack)', sku: 'CASE-12', price: '1800', reorder_level: '5' })
  await fixture('movements/', { product: low.id, quantity: '3', unit_cost: '1000' })
  await fixture('sales/checkout/', { request_id: randomUUID(), lines: [{ product: product.id, quantity: '10' }],
    discount: { kind: 'percent', value: '10' }, expected_total: '2250',
    payments: [{ method: 'cash', amount: '2250' }] })
  const category = await fixture('expense-categories/', { name: 'Transport' })
  await fixture('suppliers/', { name: 'North Wholesale' })
  const today = new Intl.DateTimeFormat('sv-SE', { timeZone: business.timezone }).format(new Date())
  await fixture('expenses/', { category: category.id, amount: '300', incurred_on: today, description: 'Fixture delivery', method: 'cash' })

  await page.getByRole('link', { name: 'Ask StockPilot AI' }).click()
  await expect(page.getByRole('heading', { name: 'AI Assistant' })).toBeVisible()
  await expect(page.getByText('Limited demonstration mode')).toBeVisible()
  await page.getByRole('button', { name: 'Check my profit', exact: false }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Gross profit' })).toContainText('₦750.00')
  await expect(page.getByRole('row').filter({ hasText: 'Net operating result' })).toContainText('₦450.00')
  await page.screenshot({ path: info.outputPath('phase3-assistant.png'), fullPage: true })
  const input = page.getByRole('textbox', { name: 'Message StockPilot AI' })
  if (process.env.STOCKPILOT_VOICE_WAV) {
    await page.context().grantPermissions(['microphone'])
    const voice = page.getByRole('dialog', { name: 'Voice input' })
    const open = page.getByRole('button', { name: 'Voice input' })
    await open.click()
    await voice.getByRole('button', { name: 'Start recording' }).click()
    await voice.getByRole('button', { name: 'Stop recording' }).click()
    await voice.getByRole('button', { name: 'Discard recording' }).click()
    await expect(input).toBeEmpty()
    await open.click()
    await voice.getByRole('button', { name: 'Start recording' }).click()
    await expect(voice.getByRole('status')).toContainText('Recording.')
    // Let the Chromium virtual microphone play the complete speech fixture.
    await page.waitForTimeout(4200)
    await voice.getByRole('button', { name: 'Stop recording' }).click()
    await expect(voice.locator('audio')).toBeVisible()
    await voice.getByRole('button', { name: 'Transcribe', exact: true }).click()
    const transcript = voice.getByRole('textbox', { name: 'Transcript' })
    await expect(transcript).toHaveValue(/water/i, { timeout: 30_000 })
    await voice.evaluate(dialog => dialog.scrollIntoView())
    await page.screenshot({ path: info.outputPath('phase4-voice-transcript.png'), fullPage: true })
    await transcript.fill('I want to sell 2 water of 75cl.')
    await voice.getByRole('button', { name: 'Use transcript' }).click()
    await expect(input).toHaveValue('I want to sell 2 water of 75cl.')
    await expect(page.getByText('How was the sale paid?')).toHaveCount(0)
  } else {
    await input.fill('I want to sell 2 water of 75cl.')
  }
  await input.press('Enter')
  await expect(page.getByText('How was the sale paid?')).toBeVisible()
  await page.getByRole('button', { name: 'Cash', exact: true }).click()
  const preview = page.getByRole('region', { name: 'Sale preview' })
  await expect(preview).toContainText('₦500.00')
  const stock = async () => (await (await page.request.get(endpoint + 'products/' + product.id + '/')).json()).stock
  expect(await stock()).toBe('90.000')
  await input.fill('Make it 5 instead.')
  await input.press('Enter')
  await expect(preview).toContainText('₦1,250.00')
  await preview.getByRole('button', { name: 'Edit preview' }).click()
  await page.getByRole('dialog').getByLabel('Quantity', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Update preview' }).click()
  await expect(preview).toContainText('₦500.00')
  await preview.scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('phase3-sale-preview.png'), fullPage: true })
  await preview.getByRole('button', { name: 'Confirm sale' }).click()
  await expect(preview.getByRole('status')).toContainText(/Sale #\d+ recorded/)
  await expect(preview.getByRole('status')).toContainText('On hand 88')
  expect(await stock()).toBe('88.000')
  await preview.scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('phase3-sale-confirmed.png'), fullPage: true })

  await page.reload()
  await expect(preview.getByRole('status')).toContainText('On hand 88')
  await page.getByRole('button', { name: 'New conversation' }).click()
  await expect(page.getByRole('heading', { name: 'Start with a business question' })).toBeVisible()
  await page.getByRole('button', { name: 'Find low stock', exact: false }).click()
  await expect(page.getByRole('row').filter({ hasText: 'CASE-12' })).toContainText('3.000')
  await page.getByRole('button', { name: 'Check my profit', exact: false }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Gross profit' })).toContainText('₦950.00')
  await expect(page.getByRole('row').filter({ hasText: 'Net operating result' })).toContainText('₦650.00')
  await input.fill('Record 50 naira as transport expense in cash')
  await page.getByRole('button', { name: 'Send message' }).click()
  const expense = page.getByRole('region', { name: 'Expense preview' })
  await expect(expense).toContainText('₦50.00')
  await expense.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(expense).toContainText('Proposal cancelled.')
  const costs = await (await page.request.get(endpoint + 'expenses/')).json()
  expect(costs.count).toBe(1)
  await input.fill('I have stocked up 100 units of water-75.')
  await input.press('Enter')
  await page.getByRole('button', { name: 'Purchase receipt', exact: true }).click()
  await expect(page.getByText(/Which supplier should I use/)).toBeVisible()
  await input.fill('North Wholesale')
  await input.press('Enter')
  await expect(page.getByText(/What was the purchase cost/)).toBeVisible()
  await input.fill('180 each')
  await input.press('Enter')
  const receipt = page.getByRole('region', { name: 'Purchase receipt preview' })
  await expect(receipt).toContainText('₦18,000.00')
  expect(await stock()).toBe('88.000')
  await receipt.scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('assistant-restock-preview.png'), fullPage: true })
  await receipt.getByRole('button', { name: 'Confirm purchase receipt' }).click()
  await expect(receipt.getByRole('status')).toContainText('On hand 188')
  expect(await stock()).toBe('188.000')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await expect(page.getByRole('complementary', { name: 'Conversation history' })).toBeVisible()
  const history = page.getByRole('complementary', { name: 'Conversation history' })
  await history.getByRole('searchbox', { name: 'Search conversations' }).fill('profit did I')
  await expect(history.getByRole('button', { name: /How much profit did I/ })).toHaveCount(1)
  await expect(history.getByRole('button', { name: /Which products are running low/ })).toHaveCount(0)
})

test('voice permission fallback preserves typed text and sends nothing', async ({ page, context, browserName }, info) => {
  test.skip(browserName !== 'chromium', 'Permission denial is configured through Chromium CDP.')
  await page.setViewportSize({ width: 390, height: 844 })
  const username = 'voice-' + randomUUID().slice(0, 8)
  await page.goto('/register')
  await page.getByLabel('Business name').fill('Voice Permission Test')
  await page.getByLabel('Username').fill(username)
  await page.getByLabel('Email').fill(username + '@example.invalid')
  await page.getByLabel('Password', { exact: true }).fill('Fixture!Wavelength459')
  if (await page.getByLabel('Confirm Password', { exact: true }).count()) await page.getByLabel('Confirm Password', { exact: true }).fill('Fixture!Wavelength459')
await page.getByRole('button', { name: 'Create workspace' }).click()
  await page.getByRole('link', { name: 'Ask StockPilot AI' }).click()

  const cdp = await context.newCDPSession(page)
  const { targetInfo } = await cdp.send('Target.getTargetInfo')
  await cdp.send('Browser.setPermission', {
    permission: { name: 'microphone' }, setting: 'denied',
    origin: new URL(page.url()).origin, browserContextId: targetInfo.browserContextId,
  })
  expect(await page.evaluate(async () => (await navigator.permissions.query({ name: 'microphone' as PermissionName })).state)).toBe('denied')

  const composer = page.getByRole('textbox', { name: 'Message StockPilot AI' })
  await composer.fill('Which products are running low?')
  await page.getByRole('button', { name: 'Voice input' }).click()
  const dialog = page.getByRole('dialog', { name: 'Voice input' })
  await expect(dialog.getByRole('alert')).toContainText('Microphone permission was denied')
  await expect(dialog.getByRole('button', { name: 'Start recording' })).toBeDisabled()
  await expect(dialog.getByRole('button', { name: 'Use transcript' })).toBeDisabled()
  await page.screenshot({ path: info.outputPath('phase4-voice-fallback.png'), fullPage: true })
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(composer).toBeFocused()
  await expect(composer).toHaveValue('Which products are running low?')
  const [business] = await (await page.request.get('/api/v1/businesses/')).json()
  const path = '/api/v1/businesses/' + business.id + '/assistant/conversations/'
  expect((await (await page.request.get(path)).json()).count).toBe(0)
  await composer.press('Enter')
  await expect(page.getByText('No active tracked products are at or below their reorder level.')).toBeVisible()
  await page.addInitScript(() => Object.defineProperty(window, 'MediaRecorder', { value: undefined }))
  await page.reload()
  await page.getByRole('button', { name: 'Voice input' }).click()
  await expect(dialog.getByRole('alert')).toContainText('Microphone recording is unavailable')
  await expect(dialog.getByRole('button', { name: 'Start recording' })).toBeDisabled()
})
