import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'

test('checkout, receive a split payment, report exact profit, and process a return', async ({ page }, info) => {
  test.setTimeout(70_000)
  const username = `sales-${randomUUID().slice(0, 8)}`
  await page.goto('/register')
  await page.getByLabel('Business name').fill('Harbor Water Supply · Test Workspace')
  await page.getByLabel('Username').fill(username)
  await page.getByLabel('Email').fill(`${username}@example.invalid`)
  await page.getByLabel('Password', { exact: true }).fill('Fixture!Wavelength459')
  if (await page.getByLabel('Confirm Password', { exact: true }).count()) await page.getByLabel('Confirm Password', { exact: true }).fill('Fixture!Wavelength459')
await page.getByRole('button', { name: 'Create workspace' }).click()
  await expect(page.getByRole('heading', { name: 'Overview' })).toBeVisible()

  const workspaceResponse = await page.request.get('/api/v1/businesses/')
  const [business] = await workspaceResponse.json()
  const cookie = (await page.context().cookies()).find(value => value.name === 'csrftoken')!
  const endpoint = `/api/v1/businesses/${business.id}/`
  async function fixture(resource: string, data: object) {
    const response = await page.request.post(endpoint + resource, { data, headers: { 'X-CSRFToken': cookie.value } })
    expect(response.ok(), `Fixture ${resource} returned ${response.status()}`).toBe(true)
    return response.json()
  }
  const category = await fixture('categories/', { name: 'Drinking water' })
  const water = await fixture('products/', { name: 'Bottled Water (75cl)', sku: 'WATER-75', barcode: '70012345', category: category.id, price: '250', reorder_level: '5' })
  await fixture('movements/', { product: water.id, quantity: '100', unit_cost: '150' })
  for (const [name, sku, price] of [['Spring Water (1.5L)', 'SPRING15', '450'], ['Sparkling Water (50cl)', 'SPARK50', '350'], ['Water Case (12 pack)', 'CASE12', '2800'], ['Reusable Water Jug', 'JUG', '1800'], ['Bottle Carrier', 'CARRIER', '500']]) {
    const item = await fixture('products/', { name, sku, price, category: category.id, reorder_level: '5' })
    await fixture('movements/', { product: item.id, quantity: sku === 'CARRIER' ? '3' : '24', unit_cost: '100' })
  }
  await fixture('customers/', { name: 'Harbor Café' })
  await fixture('expense-categories/', { name: 'Transport' })

  await page.getByRole('link', { name: 'Point of sale', exact: true }).click()
  await page.getByLabel('Search POS products').fill('70012345')
  await expect(page.getByRole('button', { name: 'Add Bottled Water (75cl)' })).toBeVisible()
  await page.getByLabel('Search POS products').press('Enter')
  await page.getByLabel('Quantity for Bottled Water (75cl)').fill('10')
  await page.getByText('Invoice discount', { exact: true }).click()
  await page.getByLabel('Invoice discount type').selectOption('percent')
  await page.getByLabel('Invoice discount value').fill('10')
  await expect(page.getByRole('region', { name: 'Current sale' })).toContainText('₦2,250.00')
  await expect(page.getByText('Spring Water (1.5L)')).toBeVisible()
  await page.screenshot({ path: info.outputPath('phase2-pos.png'), fullPage: true })

  await page.getByRole('button', { name: 'Review checkout' }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Customer', { exact: true }).selectOption({ label: 'Harbor Café' })
  await dialog.getByLabel('Payment amount 1').fill('1500')
  await dialog.getByRole('button', { name: 'Add split payment' }).click()
  await dialog.getByLabel('Payment amount 2').fill('500')
  await dialog.getByLabel('Sales notes').fill('Browser acceptance sale')
  await dialog.getByRole('button', { name: 'Post sale' }).click()
  await expect(page.getByRole('heading', { name: /^Receipt #/ })).toBeVisible()
  await expect(page.getByRole('dialog')).toContainText('₦250.00')
  await page.emulateMedia({ media: 'print' })
  await expect(page.getByRole('dialog').getByText('Walk-in customer')).toHaveCount(0)
  await expect(page.getByRole('dialog').getByText('Harbor Café')).toBeVisible()
  await expect(page.getByRole('navigation')).toBeHidden()
  await page.emulateMedia({ media: 'screen' })
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('link', { name: 'Inventory', exact: true }).click()
  const item = page.getByRole('row').filter({ hasText: 'WATER-75' })
  await expect(item).toContainText('90 unit')

  await page.getByRole('link', { name: 'Customers', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Harbor Café' })).toContainText('₦250.00')
  await page.getByRole('row').filter({ hasText: 'Harbor Café' }).getByRole('link', { name: 'Sales history' }).click()
  await page.getByRole('button', { name: /^View sale #/ }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Record payment' }).click()
  await dialog.getByLabel('Payment method').selectOption('card')
  await dialog.getByRole('button', { name: 'Save payment' }).click()
  await expect(dialog.getByRole('status')).toHaveText('Payment recorded.')
  await dialog.getByRole('button', { name: 'Close dialog' }).click()

  await page.getByRole('link', { name: 'Expenses', exact: true }).click()
  await page.getByRole('button', { name: 'Record expense' }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Category', { exact: true }).selectOption({ label: 'Transport' })
  await dialog.getByLabel('Amount').fill('300')
  await dialog.getByLabel('Description').fill('Delivery transport')
  await dialog.getByRole('button', { name: 'Save expense' }).click()
  await expect(page.getByText('Delivery transport', { exact: true })).toBeVisible()

  await page.getByRole('link', { name: 'Overview', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Financial overview' })).toContainText('₦450.00')
  await page.screenshot({ path: info.outputPath('phase2-dashboard.png'), fullPage: true })
  await page.getByRole('link', { name: 'Reports', exact: true }).click()
  await page.getByLabel('Compare another period').check()
  await page.getByRole('button', { name: 'Apply report dates' }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Net operating result' })).toContainText('₦450.00')
  await expect(page.getByRole('row').filter({ hasText: 'Cost of goods sold' })).toContainText('₦1,500.00')
  await expect(page.getByRole('row').filter({ hasText: 'Gross profit' })).toContainText('₦750.00')
  const download = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Export CSV' }).click()
  expect((await download).suggestedFilename()).toBe('stockpilot-financial-report.csv')
  await page.screenshot({ path: info.outputPath('phase2-reports.png'), fullPage: true })
  await page.emulateMedia({ media: 'print' })
  await expect(page.getByRole('heading', { name: 'Period performance' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Apply report dates' })).toBeHidden()
  await page.emulateMedia({ media: 'screen' })

  await page.getByRole('navigation').getByRole('link', { name: 'Sales history' }).click()
  await page.getByRole('button', { name: /^View sale #/ }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Return items' }).click()
  await dialog.getByLabel('Return quantity for Bottled Water (75cl)').fill('2')
  await dialog.getByLabel('Reason').fill('Unopened items returned')
  await dialog.getByRole('button', { name: 'Review return' }).click()
  await expect(dialog).toContainText('Refund to record')
  await expect(dialog).toContainText('₦450.00')
  await dialog.getByLabel('Refund method').selectOption('cash')
  await dialog.getByRole('button', { name: 'Confirm return' }).click()
  await expect(dialog.getByRole('status')).toHaveText('Return recorded.')
  await dialog.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('link', { name: 'Inventory', exact: true }).click()
  await expect(item).toContainText('92 unit')
  await page.getByRole('link', { name: 'Reports', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Net operating result' })).toContainText('₦300.00')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})
