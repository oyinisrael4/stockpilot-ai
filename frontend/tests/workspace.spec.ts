import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'

test('register, manage a catalog, receive stock, and sign in again', async ({ page }, info) => {
  const suffix = randomUUID().slice(0, 8)
  const username = `browser-${suffix}`
  const password = 'Fixture!Wavelength459'
  await page.goto('/register')
  await page.getByLabel('Business name').fill('StockPilot Test Workspace')
  await page.getByLabel('Username').fill(username)
  await page.getByLabel('Email').fill(`${username}@example.invalid`)
  await page.getByLabel('Password').fill(password)
  await page.getByRole('button', { name: 'Create workspace' }).click()
  await expect(page.getByRole('heading', { name: 'Overview' })).toBeVisible()

  await page.getByRole('link', { name: 'Products', exact: true }).click()
  await page.getByRole('button', { name: 'Categories' }).click()
  await page.getByLabel('Category name').fill('Water products')
  await page.getByRole('button', { name: 'Add category' }).click()
  await expect(page.getByText('Water products')).toBeVisible()
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Add product' }).click()
  await page.getByLabel('Product name').fill('Bottled Water (75cl)')
  await page.getByLabel('SKU', { exact: true }).fill('WATER-75')
  await page.getByLabel('Category', { exact: true }).selectOption({ label: 'Water products' })
  await page.getByLabel('Selling price').fill('250')
  await page.getByLabel('Low-stock threshold').fill('10')
  await page.getByRole('button', { name: 'Create product' }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Bottled Water (75cl)' })).toContainText('Water products')
  await page.getByLabel('Search products').fill('water-75')
  await expect(page.getByRole('row').filter({ hasText: 'Bottled Water (75cl)' })).toBeVisible()

  await page.getByRole('link', { name: 'Inventory', exact: true }).click()
  await page.getByRole('button', { name: 'Opening stock' }).click()
  await page.getByLabel('Product', { exact: true }).selectOption({ label: 'Bottled Water (75cl) · WATER-75 · unit' })
  await page.getByLabel('Quantity').fill('100')
  await page.getByLabel('Unit cost').fill('150')
  await page.getByRole('button', { name: 'Record opening stock' }).click()
  await expect(page.getByRole('status')).toHaveText('Opening stock recorded.')

  await page.getByRole('link', { name: 'Suppliers', exact: true }).click()
  await page.getByRole('button', { name: 'Add supplier' }).click()
  await page.getByLabel('Supplier name').fill('Sample Wholesale')
  await page.getByRole('button', { name: 'Create supplier' }).click()
  await expect(page.getByText('Sample Wholesale')).toBeVisible()
  await page.getByRole('link', { name: 'Purchases', exact: true }).click()
  await page.getByRole('button', { name: 'Receive purchase' }).click()
  await page.getByLabel('Supplier', { exact: true }).selectOption({ label: 'Sample Wholesale' })
  await page.getByLabel('Product 1', { exact: true }).selectOption({ label: 'Bottled Water (75cl) · WATER-75 · unit' })
  await page.getByLabel('Quantity').fill('25')
  await page.getByLabel('Unit cost').fill('200')
  await page.getByRole('button', { name: 'Post receipt' }).click()
  await expect(page.getByRole('status')).toHaveText('Purchase received. Stock balances updated.')
  await page.getByRole('button', { name: 'View receipt' }).click()
  await expect(page.getByRole('dialog')).toContainText('Bottled Water (75cl)')
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('link', { name: 'Inventory', exact: true }).click()
  const product = page.getByRole('row').filter({ hasText: '125 unit' })
  await expect(product).toContainText('₦160.00')
  await page.screenshot({ path: info.outputPath('inventory-desktop.png'), fullPage: true })

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Open menu' }).click()
  await page.getByRole('link', { name: 'Overview', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Overview' })).toBeVisible()
  await expect(page.getByRole('link', { name: /^Purchase receipts/ })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.screenshot({ path: info.outputPath('overview-mobile.png'), fullPage: true })

  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
  await page.getByLabel('Username').fill(username)
  await page.getByLabel('Password').fill(password)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('heading', { name: 'Overview' })).toBeVisible()
})
