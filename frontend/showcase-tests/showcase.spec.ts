import { test, expect } from '@playwright/test'

test('static checkout, cancellation, confirmation, summary and reset stay isolated', async ({ page }) => {
  const requests: string[] = [], errors: string[] = []
  page.on('request', request => requests.push(request.url()))
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#/demo')
  await expect(page.getByText('Fictional, browser-only sandbox')).toBeVisible()
  await page.getByRole('button', { name: 'Add Spring Water 75 cl', exact: true }).click()
  await page.getByRole('button', { name: 'Review checkout' }).click()
  await page.getByRole('button', { name: 'Cancel review' }).click()
  await page.getByRole('button', { name: 'Performance', exact: true }).click()
  await expect(page.getByText('No sample sales yet.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Checkout', exact: true }).click()
  await page.getByRole('button', { name: 'Review checkout' }).click()
  await page.getByRole('button', { name: 'Confirm fictional sale', exact: true }).dblclick()
  await page.getByRole('button', { name: 'Performance', exact: true }).click()
  await expect(page.getByText('1 fictional sales', { exact: false })).toBeVisible()
  await expect(page.getByText('₦150.00', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Guided assistant', exact: true }).click()
  await page.getByRole('button', { name: 'Preview two waters' }).click()
  await page.getByRole('button', { name: 'Cancel proposal' }).click()
  await page.getByRole('button', { name: 'Summarize sample sales' }).click()
  await expect(page.getByRole('status')).toContainText('1 sales; net sales ₦350.00')
  await page.getByRole('button', { name: 'Preview two waters' }).click()
  await page.getByRole('button', { name: 'Confirm fictional proposal' }).dblclick()
  await page.getByRole('button', { name: 'Summarize sample sales' }).click()
  await expect(page.getByRole('status')).toContainText('2 sales; net sales ₦1,050.00')
  await page.getByRole('button', { name: 'Voice walkthrough' }).click()
  await expect(page.getByText('No recording or transcription', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Reset demo' }).click()
  await page.getByRole('button', { name: 'Performance', exact: true }).click()
  await expect(page.getByText('0 fictional sales', { exact: false })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Checkout', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(requests.every(url => url.startsWith('http://127.0.0.1:5198/'))).toBeTruthy()
  expect(requests.some(url => /\/api\/|11434|8000|8092/.test(url))).toBeFalsy()
  expect(errors).toEqual([])
})

test('search and stock boundaries work; tabs do not share mutable data', async ({ page, context }) => {
  await page.goto('/#/demo')
  await page.getByRole('searchbox').fill('sparkling')
  await expect(page.getByRole('button', { name: /^Add / })).toHaveCount(1)
  const add = page.getByRole('button', { name: 'Add Sparkling Water 50 cl' })
  for (let i = 0; i < 8; i++) await add.click()
  await expect(add).toBeDisabled()
  await page.getByRole('button', { name: 'Review checkout' }).click()
  await page.getByRole('button', { name: 'Confirm fictional sale' }).click()
  await expect(add).toBeDisabled()
  const other = await context.newPage()
  await other.goto('/#/demo')
  await expect(other.getByRole('button', { name: 'Add Sparkling Water 50 cl' })).toBeEnabled()
  await page.getByRole('searchbox').fill('no such item')
  await expect(page.getByText('No products match.', { exact: false })).toBeVisible()
})

test('responsive navigation, genuine captures and all static links resolve', async ({ page }) => {
  const broken: string[] = []
  page.on('response', r => { if (r.status() >= 400) broken.push(r.url()) })
  for (const width of [320, 390, 768, 1024, 1280, 1440]) {
    await page.setViewportSize({ width, height: 950 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/')
    await page.getByRole('button', { name: 'Record a sale', exact: true }).click()
    await expect(page.locator('#workflow-preview img')).toHaveJSProperty('complete', true)
    await expect(page.locator('#workflow-preview img')).toHaveJSProperty('naturalWidth', 1440)
    await expect(page.getByRole('link', { name: 'Explore interactive demo' })).toBeVisible()
    for (const name of ['See what changed', 'Ask for the breakdown']) await page.getByRole('button', { name, exact: true }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.getByRole('link', { name: 'Explore interactive demo' }).click()
    for (const tab of ['Checkout', 'Performance', 'Guided assistant', 'Voice walkthrough']) {
      await page.getByRole('button', { name: tab, exact: true }).click()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    }
    await page.getByRole('button', { name: 'Checkout', exact: true }).click()
    if ([390, 1440].includes(width)) await page.screenshot({ path: `../docs/screenshots/phase8-demo-${width}.png`, fullPage: true })
    await page.goto('/')
    if ([390, 1440].includes(width)) await page.screenshot({ path: `../docs/screenshots/phase8-showcase-${width}.png`, fullPage: true })
  }
  expect(broken).toEqual([])
  await page.goto('/')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Skip to content' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('main')).toBeInViewport()
  await expect(page.locator('main')).toBeFocused()
  await page.getByRole('link', { name: 'How it works' }).click()
  await expect(page.locator('#workflow-preview')).toBeInViewport()
  await page.getByRole('link', { name: 'See the capabilities' }).click()
  await expect(page.locator('#capabilities')).toBeInViewport()
  await expect(page.getByRole('link', { name: 'GitHub ↗' })).toHaveAttribute('href', 'https://github.com/oyinisrael4')
  await expect(page.getByRole('link', { name: 'Portfolio ↗', exact: true })).toHaveAttribute('href', 'https://israel-projects-one.vercel.app')
  await page.goto('/#/does-not-exist')
  await expect(page.getByRole('heading', { name: 'Page not found' })).toBeVisible()
})

test('project-subdirectory deployment works with the restrictive security headers', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const response = await page.goto('/stockpilot/')
  expect(response?.headers()['content-security-policy']).toContain("connect-src 'none'")
  expect(response?.headers()['permissions-policy']).toContain('microphone=()')
  await page.getByRole('link', { name: 'Explore interactive demo' }).click()
  await expect(page).toHaveURL(/\/stockpilot\/#\/demo$/)
  await page.getByRole('button', { name: 'Add Spring Water 75 cl', exact: true }).click()
  await page.getByRole('button', { name: 'Review checkout' }).click()
  await page.getByRole('button', { name: 'Confirm fictional sale' }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Review checkout' })).toBeDisabled()
  expect(await page.locator('.demo-products img').first().evaluate((node: HTMLImageElement) => node.naturalWidth)).toBeGreaterThan(0)
  expect(errors).toEqual([])
})
